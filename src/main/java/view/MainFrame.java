    private void btnExportPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportPDFActionPerformed
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Simpan Laporan PDF");
        fileChooser.setSelectedFile(new File("Laporan_LabaKu.pdf"));

        int pilihan = fileChooser.showSaveDialog(this);

        if (pilihan != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File file = fileChooser.getSelectedFile();

        if (!file.getName().toLowerCase().endsWith(".pdf")) {
            file = new File(file.getAbsolutePath() + ".pdf");
        }

        Document document = new Document(PageSize.A4.rotate());

        try {
            PdfWriter.getInstance(document, new FileOutputStream(file));
            document.open();

            Font titleFont = new Font(Font.FontFamily.HELVETICA, 18, Font.BOLD);
            Font headerFont = new Font(Font.FontFamily.HELVETICA, 9, Font.BOLD);
            Font dataFont = new Font(Font.FontFamily.HELVETICA, 8, Font.NORMAL);

            Paragraph title = new Paragraph(
                "LabaKu - Laporan Manajemen Keuangan",
                titleFont
            );
            title.setAlignment(Element.ALIGN_CENTER);
            title.setSpacingAfter(10);
            document.add(title);

            Paragraph tanggal = new Paragraph(
                "Tanggal cetak: "
                + new SimpleDateFormat("dd-MM-yyyy HH:mm").format(new Date())
            );
            tanggal.setAlignment(Element.ALIGN_RIGHT);
            tanggal.setSpacingAfter(15);
            document.add(tanggal);

            TableModel model = tblTransactions.getModel();
            PdfPTable pdfTable = new PdfPTable(model.getColumnCount());

            pdfTable.setWidthPercentage(100);
            pdfTable.setWidths(new float[]{0.7f, 1.2f, 1.2f, 1.5f, 3f, 1.8f, 1.5f});

        for (int col = 0; col < model.getColumnCount(); col++) {
            PdfPCell cell = new PdfPCell(
                new Phrase(model.getColumnName(col), headerFont)
            );
            cell.setHorizontalAlignment(Element.ALIGN_CENTER);
            cell.setPadding(6);
            pdfTable.addCell(cell);
        }

        NumberFormat rupiahFormat = NumberFormat.getCurrencyInstance(
            new Locale("id", "ID")
        );

        for (int row = 0; row < model.getRowCount(); row++) {
            for (int col = 0; col < model.getColumnCount(); col++) {
                Object value = model.getValueAt(row, col);
                String text = value == null ? "" : value.toString();

                if (col == 5 && value != null) {
                    try {
                        text = rupiahFormat.format(
                            Double.parseDouble(value.toString())
                        );
                    } catch (NumberFormatException ex) {
                    // Gunakan nilai asli jika bukan angka
                    }
                }

                PdfPCell cell = new PdfPCell(new Phrase(text, dataFont));
                cell.setPadding(5);
                pdfTable.addCell(cell);
            }
        }

        document.add(pdfTable);
        document.close();

        JOptionPane.showMessageDialog(
            this,
            "PDF berhasil disimpan!\n" + file.getAbsolutePath()
        );

        } catch (Exception e) {
        if (document.isOpen()) {
            document.close();
        }

        JOptionPane.showMessageDialog(
            this,
            "Gagal membuat PDF: " + e.getMessage(),
            "Export Gagal",
            JOptionPane.ERROR_MESSAGE
        );

            e.printStackTrace();
        }
    }//GEN-LAST:event_btnExportPDFActionPerformed

